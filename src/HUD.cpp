void HUD::init() {
    shader_ = new Shader("shaders/hud.vert", "shaders/hud.frag");

    // glyph atlas: one row of 96 cells, 8x8 pixels each, single channel
    const int W = kNumChars * kCell, H = kCell;
    std::vector<uint8_t> px(W * H, 0);
    for (const Glyph& g : kFont) {
        int cell = g.c - kFirstChar;
        for (int row = 0; row < 7; ++row)
            for (int col = 0; col < 5; ++col)
                if (g.r[row] & (0x10 >> col)) px[row * W + cell * kCell + col] = 255;
    }
    glGenTextures(1, &atlas_);
    glBindTexture(GL_TEXTURE_2D, atlas_);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, W, H, 0, GL_RED, GL_UNSIGNED_BYTE, px.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);   // crisp pixel font
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);

    glGenVertexArrays(1, &vao_); glGenBuffers(1, &vbo_);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);                   glEnableVertexAttribArray(0);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float))); glEnableVertexAttribArray(1);
    glBindVertexArray(0);
}

void HUD::begin(int screenW, int screenH) {
    w_ = screenW; h_ = screenH;
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_CULL_FACE);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    shader_->use();
    shader_->setMat4("ortho", glm::ortho(0.0f, (float)w_, (float)h_, 0.0f));
    shader_->setInt("font", 0);
    shader_->setBool("solid", false);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, atlas_);
}

void HUD::end() {
    glDisable(GL_BLEND);
    glEnable(GL_CULL_FACE);
    glEnable(GL_DEPTH_TEST);
}

void HUD::drawString(const std::string& s, float x, float y, float scale, const glm::vec4& color) {
    std::vector<float> v;
    v.reserve(s.size() * 24);
    float cx = x;
    for (char ch : s) {
        unsigned char u = (unsigned char)std::toupper((unsigned char)ch);
        int cell = (u >= kFirstChar && u < kFirstChar + kNumChars) ? u - kFirstChar : 0;
        float u0 = (float)(cell * kCell) / (kNumChars * kCell);
        float u1 = (float)(cell * kCell + 7) / (kNumChars * kCell);     // 7 rows tall, 5 wide: use 7x7 cell area
        float w = 7 * scale, h = 7 * scale;
        float q[24] = {
            cx,     y,     u0, 0.0f,   cx + w, y,     u1, 0.0f,   cx + w, y + h, u1, 7.0f / kCell,
            cx,     y,     u0, 0.0f,   cx + w, y + h, u1, 7.0f / kCell,   cx,     y + h, u0, 7.0f / kCell };
        v.insert(v.end(), q, q + 24);
        cx += 6 * scale;
    }
    shader_->setVec4("color", color);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glBufferData(GL_ARRAY_BUFFER, v.size() * sizeof(float), v.data(), GL_STREAM_DRAW);
    glDrawArrays(GL_TRIANGLES, 0, (GLsizei)(v.size() / 4));
    glBindVertexArray(0);
}

void HUD::text(const std::string& s, float x, float y, float scale, const glm::vec3& color, float alpha) {
    drawString(s, x + scale, y + scale, scale, glm::vec4(0, 0, 0, alpha * 0.8f));   // drop shadow for readability
    drawString(s, x, y, scale, glm::vec4(color, alpha));
}

void HUD::textCentered(const std::string& s, float y, float scale, const glm::vec3& color) {
    text(s, (w_ - textWidth(s, scale)) * 0.5f, y, scale, color);
}

void HUD::rect(float x, float y, float w, float h, const glm::vec4& color) {
    float q[24] = { x, y, 0, 0,   x + w, y, 0, 0,   x + w, y + h, 0, 0,
                    x, y, 0, 0,   x + w, y + h, 0, 0,   x, y + h, 0, 0 };
    shader_->setBool("solid", true);
    shader_->setVec4("color", color);
    glBindVertexArray(vao_);
    glBindBuffer(GL_ARRAY_BUFFER, vbo_);
    glBufferData(GL_ARRAY_BUFFER, sizeof(q), q, GL_STREAM_DRAW);
    glDrawArrays(GL_TRIANGLES, 0, 6);
    glBindVertexArray(0);
    shader_->setBool("solid", false);
}
